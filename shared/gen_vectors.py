"""Fill in the hex of every status vector in shared/vectors.json and write the C++ test header.

The hex is computed here with Python's struct module from each vector's `expect` fields, independently of the
Swift and C++ encoders, so both of those are checked against a third implementation.

    python -I shared/gen_vectors.py          # update vectors.json "hex" fields + firmware/test/test_protocol/vectors_gen.h
    python -I shared/gen_vectors.py --check  # exit 1 if either is out of date (CI)
"""
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VECTORS = ROOT / "shared" / "vectors.json"
HEADER = ROOT / "firmware" / "test" / "test_protocol" / "vectors_gen.h"

# (field, struct code); None = reserved byte, always 0
LAYOUT = [
    ("version", "B"), ("flags", "B"), ("seq", "H"),
    ("battAge", "B"), ("socPct", "B"), ("battCentiVolts", "H"), ("battDeciAmps", "h"), ("battMinutes", "H"),
    ("chgAge", "B"), (None, "B"), ("solarWatts", "H"), ("truckWatts", "H"), ("chgDeciAmps", "h"),
    ("invAge", "B"), ("invBits", "B"), ("invWatts", "H"),
    ("circAge", "B"), ("circOn", "B"), ("circConfirmed", "B"), ("circReady", "B"),
    ("fanAge", "B"), ("fanMode", "B"), ("fanPct", "B"), (None, "B"),
    ("boxDeciC", "h"), ("cutCountdownS", "H"),
]
FMT = "<" + "".join(code for _, code in LAYOUT)
FIELDS = [name for name, _ in LAYOUT if name]
assert struct.calcsize(FMT) == 36


def pack(expect):
    missing = [f for f in FIELDS if f not in expect]
    extra = [k for k in expect if k not in FIELDS]
    if missing or extra:
        raise SystemExit(f"bad expect: missing {missing}, unknown {extra}")
    return struct.pack(FMT, *[expect[name] if name else 0 for name, _ in LAYOUT])


def build(data):
    by_name = {}
    for v in data["status"]:
        if v["valid"]:
            raw = pack(v["expect"])
        else:
            base = bytearray(by_name[v["from"]])
            if "version" in v:
                base[0] = v["version"]
            if "truncate" in v:
                base = base[: v["truncate"]]
            raw = bytes(base)
        by_name[v["name"]] = raw
        v["hex"] = raw.hex()
    return data


def c_bytes(raw):
    return "{" + ", ".join(f"0x{b:02x}" for b in raw) + "}" if raw else "{0}"


def header(data):
    out = ["// GENERATED by shared/gen_vectors.py from shared/vectors.json. Do not edit.", "#pragma once",
           "#include <stddef.h>", "#include <stdint.h>", '#include "protocol.h"', ""]
    for v in data["status"]:
        if v["valid"]:
            out.append(f"static void expect_{v['name']}(StatusRecord& r) {{")
            for f in FIELDS:
                out.append(f"  r.{f} = {v['expect'][f]};")
            out.append("}")
    out.append("")
    out.append("struct StatusVector { const char* name; uint8_t bytes[36]; size_t len; bool valid; void (*expect)(StatusRecord&); };")
    out.append("static const StatusVector kStatusVectors[] = {")
    for v in data["status"]:
        raw = bytes.fromhex(v["hex"])
        fn = f"expect_{v['name']}" if v["valid"] else "nullptr"
        out.append(f'  {{"{v["name"]}", {c_bytes(raw)}, {len(raw)}, {"true" if v["valid"] else "false"}, {fn}}},')
    out.append("};")
    out.append("")
    out.append("struct CommandVector { const char* name; uint8_t bytes[4]; size_t len; bool valid; };")
    out.append("static const CommandVector kCommandVectors[] = {")
    for c in data["commands"]:
        raw = bytes.fromhex(c["hex"])
        out.append(f'  {{"{c["name"]}", {c_bytes(raw)}, {len(raw)}, {"true" if c["valid"] else "false"}}},')
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    old_json = VECTORS.read_text(encoding="utf-8")
    data = build(json.loads(old_json))
    new_json = json.dumps(data, indent=2) + "\n"
    new_header = header(data)
    if check:
        stale = []
        if json.loads(old_json) != json.loads(new_json):
            stale.append(str(VECTORS))
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != new_header:
            stale.append(str(HEADER))
        if stale:
            print("out of date (run python -I shared/gen_vectors.py):", *stale, sep="\n  ")
            sys.exit(1)
        print("vectors up to date")
        return
    VECTORS.write_text(new_json, encoding="utf-8", newline="\n")
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(new_header, encoding="utf-8", newline="\n")
    print("wrote", VECTORS, "and", HEADER)


if __name__ == "__main__":
    main()
